-- REVIEW ONLY: PostgreSQL design preview, not an executable application migration.
-- Selected reading/comics tables plus migration ledgers, NOT all 27 business tables.
-- Not executed against the user's database. Full schema is implemented after review.
BEGIN;
CREATE SCHEMA mediahub;
SET LOCAL search_path TO mediahub;

CREATE TABLE schema_migrations (
    version bigint PRIMARY KEY,
    checksum text NOT NULL,
    applied_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE data_migrations (
    id text PRIMARY KEY,
    source_kind text NOT NULL,
    source_fingerprint text NOT NULL,
    started_at timestamptz NOT NULL,
    completed_at timestamptz,
    verification jsonb NOT NULL
);

CREATE TABLE reading_items (
    id text PRIMARY KEY,
    kind text NOT NULL CHECK (kind IN ('comics', 'novels')),
    root text NOT NULL,
    path text NOT NULL,
    title text NOT NULL,
    format text NOT NULL,
    size bigint NOT NULL CHECK (size >= 0),
    modified_at timestamptz NOT NULL,
    imported_at timestamptz NOT NULL,
    available boolean NOT NULL DEFAULT true,
    UNIQUE (kind, root, path)
);
CREATE INDEX idx_reading_kind_title ON reading_items (kind, lower(title), id);
CREATE INDEX idx_reading_recent ON reading_items (kind, imported_at DESC, id);

CREATE TABLE reading_comic_duplicates (
    alias_id text PRIMARY KEY,
    canonical_id text REFERENCES reading_items(id),
    CHECK (alias_id <> canonical_id)
);
-- canonical_id NULL means the former duplicate relationship is inactive.
-- alias_id can identify an archive suppressed before insertion into reading_items.

CREATE TABLE reading_covers (
    item_id text PRIMARY KEY REFERENCES reading_items(id),
    size bigint NOT NULL,
    modified_at timestamptz NOT NULL,
    content_type text NOT NULL,
    image bytea NOT NULL
);

CREATE TABLE reading_scans (
    kind text PRIMARY KEY,
    completed_at timestamptz NOT NULL,
    found bigint NOT NULL CHECK (found >= 0)
);

CREATE TABLE comic_metadata (
    item_id text PRIMARY KEY REFERENCES reading_items(id),
    gallery_id text NOT NULL,
    token text NOT NULL,
    site text NOT NULL CHECK (site IN ('e-hentai.org', 'exhentai.org')),
    title text NOT NULL,
    japanese_title text NOT NULL DEFAULT '',
    cover text NOT NULL DEFAULT '',
    category text NOT NULL DEFAULT '',
    uploader text NOT NULL DEFAULT '',
    posted text NOT NULL DEFAULT '', -- raw source text; no invented timezone
    language text NOT NULL DEFAULT '',
    rating text NOT NULL DEFAULT '', -- preserve values such as "Average: 4.43"
    pages integer NOT NULL CHECK (pages >= 0),
    fetched_at timestamptz NOT NULL,
    current_tag_revision text NOT NULL -- preserve existing revision identities
);
CREATE INDEX idx_comic_gallery ON comic_metadata (site, gallery_id, token);

CREATE TABLE comic_metadata_tags (
    item_id text NOT NULL REFERENCES comic_metadata(item_id),
    revision text NOT NULL,
    namespace text NOT NULL,
    tag text NOT NULL,
    PRIMARY KEY (item_id, revision, namespace, tag)
);
CREATE INDEX idx_comic_tag_lookup ON comic_metadata_tags (namespace, tag, item_id);

-- Other domains retain their existing table identities. Examples of adaptations:
-- users.account: text, with UNIQUE INDEX ON users(lower(account)).
-- activity_logs.id / download_events.id: bigint GENERATED BY DEFAULT AS IDENTITY.
-- JSON payload columns: jsonb; encrypted settings.value remains text.
-- Sessions expires_at: bigint Unix seconds; all actual instants: timestamptz.
-- No TRUNCATE, DROP, data deletion, default-account insertion or remote execution.
ROLLBACK; -- Review script never commits schema changes if run manually.
